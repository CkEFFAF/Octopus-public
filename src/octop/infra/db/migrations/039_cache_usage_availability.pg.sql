-- Session activity stores identifiers and timestamps, never message bodies.
CREATE TABLE IF NOT EXISTS thread_user_activity (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 source_id TEXT NOT NULL,
 occurred_at DOUBLE PRECISION NOT NULL,
 source_kind TEXT NOT NULL DEFAULT 'input',
 UNIQUE(owner_user_id,thread_id,source_id)
);
CREATE INDEX IF NOT EXISTS thread_activity_owner_time ON thread_user_activity(owner_user_id,occurred_at);
CREATE INDEX IF NOT EXISTS thread_activity_agent_time ON thread_user_activity(owner_user_id,agent_id,occurred_at,thread_id);

