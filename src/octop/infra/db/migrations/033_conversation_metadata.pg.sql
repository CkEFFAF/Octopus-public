ALTER TABLE threads ADD COLUMN IF NOT EXISTS title_revision INTEGER NOT NULL DEFAULT 0;
ALTER TABLE threads ADD COLUMN IF NOT EXISTS title_updated_at DOUBLE PRECISION NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS thread_metadata (
 thread_id TEXT PRIMARY KEY REFERENCES threads(thread_id) ON DELETE CASCADE,
 revision INTEGER NOT NULL DEFAULT 0,
 source_revision INTEGER NOT NULL DEFAULT 0,
 message_revision INTEGER NOT NULL DEFAULT 0,
 activity_revision INTEGER NOT NULL DEFAULT 0,
 artifact_revision INTEGER NOT NULL DEFAULT 0,
 generated_source_revision INTEGER NOT NULL DEFAULT -1,
 auto_enrolled INTEGER NOT NULL DEFAULT 0,
 dirty INTEGER NOT NULL DEFAULT 0,
 snapshot_json TEXT NOT NULL DEFAULT '{}',
 manual_json TEXT NOT NULL DEFAULT '{}',
 generated_at DOUBLE PRECISION NOT NULL DEFAULT 0,
 last_error TEXT NOT NULL DEFAULT ''
);
INSERT INTO thread_metadata(thread_id) SELECT thread_id FROM threads WHERE 1=1 ON CONFLICT(thread_id) DO NOTHING;
CREATE TABLE IF NOT EXISTS thread_metadata_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id TEXT NOT NULL UNIQUE,
 dedup_key TEXT NOT NULL UNIQUE,
 owner_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 agent_id TEXT NOT NULL REFERENCES agents(agent_id) ON DELETE CASCADE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 kind TEXT NOT NULL,
 request_json TEXT NOT NULL DEFAULT '{}',
 status TEXT NOT NULL DEFAULT 'queued',
 attempts INTEGER NOT NULL DEFAULT 0,
 not_before DOUBLE PRECISION NOT NULL DEFAULT 0,
 lease_until DOUBLE PRECISION NOT NULL DEFAULT 0,
 lease_token TEXT NOT NULL DEFAULT '',
 result_json TEXT NOT NULL DEFAULT '{}',
 error_code TEXT NOT NULL DEFAULT '',
 created_at DOUBLE PRECISION NOT NULL,
 updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_metadata_jobs_due ON thread_metadata_jobs(status,not_before,lease_until);
CREATE INDEX IF NOT EXISTS idx_metadata_jobs_scope ON thread_metadata_jobs(owner_user_id,agent_id,thread_id,id);
CREATE TABLE IF NOT EXISTS thread_semantic_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id TEXT NOT NULL UNIQUE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 source_key TEXT NOT NULL,
 kind TEXT NOT NULL,
 occurred_at DOUBLE PRECISION NOT NULL,
 recorded_at DOUBLE PRECISION NOT NULL,
 payload_json TEXT NOT NULL,
 UNIQUE(thread_id,source_key)
);
CREATE INDEX IF NOT EXISTS idx_semantic_events_time ON thread_semantic_events(thread_id,occurred_at,event_id);
CREATE TABLE IF NOT EXISTS thread_digests (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 digest_id TEXT NOT NULL UNIQUE,
 thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
 cache_key TEXT NOT NULL UNIQUE,
 source_revision INTEGER NOT NULL,
 payload_json TEXT NOT NULL,
 created_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_thread_digests_scope ON thread_digests(thread_id,id);
